import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { spawnSync } from 'node:child_process';
import { latestClosedSession } from './market-calendar.mjs';
import { cdsObservation, parseCdsHistory, refreshCdsDaily } from './cds-refresh.mjs';
const source = { entityId: 'INTC', ticker: 'INTC5YUSAX', url: 'https://www.investing.com/rates-bonds/intel-corp-cds-5-year-usd-historical-data', sourceId: 'investing', tenor: '5Y', currency: 'USD' };
const row = (date, close, open = close) => `<tr><td>${date}</td><td>${close}</td><td>${open}</td><td>${Math.max(close, open)}</td><td>${Math.min(close, open)}</td><td>+0.46%</td></tr>`;
const html = `<h1>Intel Corp CDS 5 Year USD (INTC5YUSAX)</h1><table>${row('Nov 18, 2026', 148.210, 147.537)}${row('Nov 17, 2026', 147.536, 147.862)}${row('Nov 25, 2026', 152)}</table>`;
assert.deepEqual(parseCdsHistory(html, source.ticker, '2026-11-24').map(r => r.date), ['2026-11-17', '2026-11-18']);
assert.throws(() => parseCdsHistory(html, 'MSFT5YUSAX', '2026-11-24'), /identity/);
assert.throws(() => parseCdsHistory('<h1>INTC5YUSAX</h1>captcha', source.ticker, '2026-11-24'));
assert.throws(() => parseCdsHistory(html.replace('<td>148.21</td>', '<td>NaN</td>'), source.ticker, '2026-11-24'));
const existing = cdsObservation(source, { date: '2026-11-17', close: 147.536, open: 147.862, high: 147.862, low: 147.536, changePct: -0.22 }, '2026-11-20T00:00:00Z');
const prior = { observations: [existing], checks: [], events: [] };
const now = new Date('2026-11-25T05:00:00Z');
const success = async () => ({ ok: true, text: async () => html });
const updated = await refreshCdsDaily({ dailySources: [source] }, prior, '2026-11-24', now, success);
assert.equal(updated.observations.length, 2);
assert.deepEqual(updated.observations[0], existing);
assert.equal(prior.observations.length, 1);
assert.equal(updated.checkStatus, 'partial');
assert.equal(updated.dailyCheck.sources[0].status, 'lagging');
assert.equal(updated.dailyCheck.sources[0].latestDate, '2026-11-18');
assert.equal((await refreshCdsDaily({ dailySources: [source] }, updated, '2026-11-24', now, success)).dailyCheck.added, 0);
const failed = await refreshCdsDaily({ dailySources: [source] }, prior, '2026-11-24', now, async () => ({ ok: false, status: 403 }));
assert.deepEqual(failed.observations, prior.observations);
assert.equal(failed.dailyCheck.sources[0].status, 'unavailable');
assert.equal(failed.dailyCheck.sources[0].latestDate, '2026-11-17');
const mismatch = await refreshCdsDaily({ dailySources: [source] }, prior, '2026-11-24', now, async () => ({ ok: true, text: async () => html.replaceAll('147.536', '137.536') }));
assert.equal(mismatch.dailyCheck.sources[0].status, 'unavailable');
assert.deepEqual(mismatch.observations, prior.observations);
// End-to-end regression: up-to-date equity bars must not short-circuit the CDS check.
const directory = await mkdtemp(join(tmpdir(), 'cds-refresh-test-'));
try {
  await mkdir(join(directory, '.github')); await mkdir(join(directory, 'sox-public'));
  const session = latestClosedSession(new Date());
  const prices = Object.fromEntries(['QQQ', 'SPY', 'GSPC', 'IXIC'].map(key => [key, [[session, 100, 100]]]));
  const cds = { checkedAt: '2026-11-20T00:00:00Z', checkStatus: 'partial', checkNote: 'Fixture', observations: [], events: [], checks: [] };
  await writeFile(join(directory, '.github/close-snapshot.json'), JSON.stringify({ schemaVersion: 1, completedOn: session, prices, sox: [{ date: session, close: 100 }], cds }));
  await writeFile(join(directory, 'seed.json'), JSON.stringify({ schemaVersion: 1, ...cds, entities: [{ id: 'INTC' }], dailySources: [source] }));
  await writeFile(join(directory, 'sox-market-seed.json'), JSON.stringify({ bars: [{ date: session, close: 100 }] }));
  await writeFile(join(directory, 'sox-public/timing-prices.json'), JSON.stringify(prices));
  for (const key of ['gspc', 'ixic']) await writeFile(join(directory, 'sox-public/timing-' + key + '.json.gz'), gzipSync(JSON.stringify([[session, 10000]])));
  const code = `let checks=0; globalThis.fetch=async url=>{ if(url.endsWith('/api/snapshot'))return {ok:true,json:async()=>(${JSON.stringify({ schemaVersion: 1, ...cds })})}; if(url.startsWith('https://www.investing.com/')){checks++;return {ok:false,status:403};} throw Error('Unexpected equity request: '+url);}; process.argv[2]='refresh'; await import(${JSON.stringify(new URL('./close-snapshot.mjs', import.meta.url).href)}); if(checks!==1)throw Error('CDS was skipped');`;
  const child = spawnSync(process.execPath, ['--input-type=module', '-e', code], { cwd: directory, encoding: 'utf8' });
  assert.equal(child.status, 0, child.stderr + child.stdout);
  const saved = JSON.parse(await readFile(join(directory, '.github/close-snapshot.json'), 'utf8'));
  assert.equal(saved.refresh.marketStatus, 'ok');
  assert.equal(saved.refresh.cdsStatus, 'partial');
  assert.equal(saved.refresh.status, 'partial');
  assert.equal(saved.cds.dailyCheck.targetSession, session);
  assert.equal(saved.cds.dailyCheck.sources[0].status, 'unavailable');
} finally { await rm(directory, { recursive: true, force: true }); }
console.log('CDS refresh tests passed, including independent checks when equity closes are already current.');
